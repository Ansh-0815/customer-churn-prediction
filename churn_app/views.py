def get_saved_metrics():
    metrics_path = "models/metrics.json"
    if os.path.exists(metrics_path):
        try:
            with open(metrics_path, 'r') as f:
                return json.load(f)
        except Exception:
            pass
    # Baseline fallback if metrics.json not yet generated by retraining
    return {
        "accuracy": 0.793,
        "precision": 0.638,
        "recall": 0.528,
        "f1": 0.578,
        "roc_auc": 0.843
    }

